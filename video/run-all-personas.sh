#!/bin/bash
# שלב 11 — שלוש פרסונות × שני רוחבים, ברצף.
# ברצף ולא במקביל: שלושה דפדפנים בו-זמנית הם בדיוק מה שמיצה את בריכת
# החיבורים והפיל את פרודקשן בלילה 4→5.9.
set -u
cd "$(dirname "$0")/.."
for P in y1 y2 y3; do
  echo ""
  echo "████████ פרסונה $P ████████"
  # **כל** פרסונה נזרעת, כולל y1. הרנר הניח קודם ש-y1 כבר על החשבון,
  # אבל החשבון הוא מה שהפרסונה הקודמת השאירה — ושער הפרסונה היה דוחה
  # את הסיור בצדק. הזריעה היא חלק מהסיור, לא הכנה לו.
  if true; then
    # הזריעה של y2/y3 סורקת גיליון ציונים דרך ה-AI, ו-429 מ-Gemini מפיל
    # אותה בחריגת זמן. שלושה ניסיונות, ואם כולם נכשלו — **מדלגים על
    # הפרסונה** במקום לסייר על חשבון ריק ולתייג אותו "שנה ב׳".
    ok=0
    for attempt in 1 2 3; do
      npm run reset:test 2>&1 | tail -1
      if node video/persona-seed.mjs --persona "$P" 2>&1 | tail -4 | grep -q "מצב סופי"; then
        ok=1; break
      fi
      echo "  ↻ זריעת $P נכשלה (ניסיון $attempt)"
    done
    if [ "$ok" -eq 0 ]; then
      echo "❌ זריעת $P נכשלה שלוש פעמים — מדלג על הפרסונה, בלי נתונים מתויגים לא נכון"
      continue
    fi
  fi
  for W in 1440 390; do
    echo "──── $P · ${W}px ────"
    node video/final-personas.mjs --persona "$P" --width "$W" 2>&1 | tail -30
  done
done
echo ""
echo "████████ כל הסיורים הסתיימו ████████"
