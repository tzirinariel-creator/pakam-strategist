import { openApp, login, shot, BASE } from "./tour-lib.mjs";
const { b, p, errors } = await openApp({ width: 1440, height: 1000 });
const net = [];
p.on("response", (r) => { const u = r.url(); if (u.includes("/api/") && r.status() >= 400) net.push(`HTTP ${r.status()} ${u.replace(BASE,"").slice(0,110)}`); });
p.on("console", (m) => { if (m.type() === "error") net.push("CONSOLE " + m.text().slice(0, 200)); });
await login(p); await p.waitForTimeout(6000);
await p.goto(`${BASE}/he/lineage`, { waitUntil: "networkidle" });
await p.waitForTimeout(10000);
const t = (await p.locator("body").innerText()).replace(/\s+/g, " ");
console.log("אורך הטקסט על המסך:", t.length);
console.log("תוכן:", t.slice(0, 500) || "(ריק לגמרי)");
const dom = await p.evaluate(() => {
  const main = document.querySelector("main") || document.body;
  return { childCount: main.children.length, html: main.innerHTML.slice(0, 400) };
});
console.log("\nילדי main:", dom.childCount);
console.log("HTML:", dom.html);
console.log("\nרשת/קונסולה:", net.length ? [...new Set(net)].join("\n  ") : "נקי");
console.log("שגיאות דף:", errors.length ? [...new Set(errors)].join(" | ") : "אין");
console.log(await shot(p, "lineage-probe", { full: true }));
await b.close();
