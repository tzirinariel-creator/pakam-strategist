import { openApp, login, shot, BASE } from "./tour-lib.mjs";
const { b, p } = await openApp({ width: 390, height: 844, mobile: true });
const settle=async(ms=8000)=>{await p.waitForTimeout(ms);await p.waitForFunction(()=>!document.querySelector("[class*=animate-pulse]"),{timeout:45000}).catch(()=>{});};
await login(p); await settle(5000);
await p.goto(`${BASE}/he/exam-planner`,{waitUntil:"networkidle"}); await settle();
const t=(await p.locator("body").innerText()).replace(/\s+/g," ");
console.log("אורך:", t.length);
console.log("יש 'הלוח השבועי שלכם'? ", /הלוח השבועי שלכם/.test(t));
console.log("יש 'תקופת המבחנים שלכם'? ", /תקופת המבחנים שלכם/.test(t));
console.log("יש 'האג׳נדה'/'מטלות'? ", /אג׳נדה|מטלות|דחו יום/.test(t));
console.log("בלוקי גרירה:", await p.locator('button[aria-label^="גררו את הלמידה"]').count());
console.log("כפתורי 'דחו יום':", await p.locator("button").filter({hasText:/^דחו יום$/}).count());
console.log("\nמסך:", t.slice(0,600));
console.log(await shot(p,"mobile-exam",{full:true}));
await b.close();
