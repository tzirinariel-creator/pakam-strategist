import { openApp, login, shot, BASE } from "./tour-lib.mjs";
const { b, p } = await openApp({ width: 1440, height: 1100 });
const settle=async(ms=7000)=>{await p.waitForTimeout(ms);await p.waitForFunction(()=>!document.querySelector("[class*=animate-pulse]"),{timeout:45000}).catch(()=>{});};
const calls=[];
p.on("request", r => { const u=r.url(); if(u.includes("/api/trpc")){ const m=u.match(/trpc\/([^?]+)/); calls.push(decodeURIComponent(m?.[1]??"").slice(0,70)); }});
p.on("response", async r => { if(r.status()>=400 && r.url().includes("/api/")){ let t=""; try{t=(await r.text()).slice(0,250);}catch{} calls.push(`  ‼️ ${r.status()} ${t}`);} });
await login(p); await settle(5000);
await p.goto(`${BASE}/he/miluim`,{waitUntil:"networkidle"}); await settle();
const rows = async () => p.evaluate(()=>[...document.querySelectorAll("tbody tr")].map(r=>r.innerText.replace(/\s+/g," ").trim()));
console.log("לפני:", JSON.stringify(await rows(),null,1));
calls.length=0;
const del = p.getByRole("button",{name:/^מחקו את תשפ״ז/}).first();
console.log("כפתור המחיקה:", await del.count() ? "נמצא" : "לא נמצא");
await del.click();
await p.waitForTimeout(2500);
console.log("מיד אחרי הלחיצה:", JSON.stringify(await rows(),null,1));
console.log("קריאות:", JSON.stringify(calls));
const save = p.getByRole("button",{name:/^שמירת מילואים$/}).first();
console.log("כפתור שמירה:", await save.count() ? "נמצא" : "לא נמצא");
if (await save.count()) { await save.click(); await p.waitForTimeout(6000); }
console.log("אחרי שמירה:", JSON.stringify(await rows(),null,1));
console.log("קריאות:", JSON.stringify(calls,null,1));
await p.reload({waitUntil:"networkidle"}); await settle();
console.log("אחרי רענון:", JSON.stringify(await rows(),null,1));
console.log(await shot(p,"miluim-del-probe",{full:true}));
await b.close();
