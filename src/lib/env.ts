// 6.9 — אריאל: *"היה איזשהו פאק בסנכרון ליומן... כן החיבור לא עובד."*
//
// הוא לא עבד מעולם בפרודקשן, ולא בגלל הקוד. שמונה משתני-סביבה בפרודקשן
// נשמרו עם **תו שורה חדשה בסוף הערך** — כנראה מהדבקה מהטרמינל. אחד מהם
// הוא `GOOGLE_REDIRECT_URI`, וגוגל דוחה את הבקשה בגללו. זה מפורשות מה
// שגוגל עצמה החזירה, כשפענחתי את מטען-השגיאה שלה:
//
//     redirect_uri = "https://pakam-strategist.vercel.app/api/google/callback\n"
//     → invalid_request · "doesn't comply with Google's OAuth 2.0 policy"
//
// תו אחד בלתי-נראה בסוף מחרוזת, וכל תכונת "סנכרון ליומן" מתה. לוג השרת לא
// הראה כלום — הכישלון קרה אצל גוגל, לא אצלנו, והמשתמש קיבל מסך שגיאה
// בעברית של גוגל שאין לו שום קשר לאפליקציה.
//
// לתקן את הערך ב-Vercel זה נכון וגם נעשה; אבל ערך שמגיע מבחוץ הוא קלט,
// והקלט הזה יידבק שוב מתישהו. חיתוך בקוד הוא ההגנה שנשארת.

/** ערך משתנה-סביבה, חתוך משני הצדדים; undefined כשהוא ריק או חסר. */
export function env(name: string): string | undefined {
  const v = process.env[name];
  if (typeof v !== "string") return undefined;
  const t = v.trim();
  return t === "" ? undefined : t;
}

/** כמו env(), עם ברירת מחדל. */
export function envOr(name: string, fallback: string): string {
  return env(name) ?? fallback;
}
